// purge-phosphor.js
const fs = require('fs');
const path = require('path');

function getFiles(dir, fileList = []) {
  if (!fs.existsSync(dir)) return fileList;
  const files = fs.readdirSync(dir);
  for (const file of files) {
    const filePath = path.join(dir, file);
    if (fs.statSync(filePath).isDirectory()) {
      getFiles(filePath, fileList);
    } else {
      fileList.push(filePath);
    }
  }
  return fileList;
}

// 1. Scan templates and JS files for used icons
const templateDir = path.resolve(__dirname, 'src/main/resources/templates');
const jsDir = path.resolve(__dirname, 'src/main/resources/static/js');

const files = [...getFiles(templateDir), ...getFiles(jsDir)];
const usedIcons = new Set();

const iconRegex = /\bph-([a-zA-Z0-9-]+)\b/g;

for (const file of files) {
  // Skip binary/compiled files if any
  if (file.endsWith('.html') || file.endsWith('.js')) {
    const content = fs.readFileSync(file, 'utf8');
    let match;
    while ((match = iconRegex.exec(content)) !== null) {
      const icon = match[1];
      // Skip helper/base/unrelated classes
      if (icon !== 'bold' && icon !== 'fill' && icon !== 'regular' && icon !== 'duotone' && icon !== 'thin' && icon !== 'light' && icon !== 'spin') {
        usedIcons.add(icon);
      }
    }
  }
}

console.log(`Found ${usedIcons.size} unique icons used in the project.`);

// 2. Load Phosphor stylesheets
const boldCssPath = path.resolve(__dirname, 'node_modules/@phosphor-icons/web/src/bold/style.css');
const fillCssPath = path.resolve(__dirname, 'node_modules/@phosphor-icons/web/src/fill/style.css');

if (!fs.existsSync(boldCssPath) || !fs.existsSync(fillCssPath)) {
  console.error("Phosphor Icons stylesheets not found in node_modules! Run npm install first.");
  process.exit(1);
}

const boldCss = fs.readFileSync(boldCssPath, 'utf8');
const fillCss = fs.readFileSync(fillCssPath, 'utf8');

// Helper to parse rules from style.css
// Formats:
// .ph-bold.ph-xxx:before {
//   content: "\exxx";
// }
function extractRules(css, prefix, icons) {
  const rules = [];
  const escapedPrefix = prefix.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&');
  
  for (const icon of icons) {
    // Regex matches .ph-bold.ph-xxx:before { ... }
    const regexStr = `\\.ph-${escapedPrefix}\\.ph-${icon}:before\\s*\\{[^\\}]+\\}`;
    const regex = new RegExp(regexStr, 'g');
    const match = css.match(regex);
    if (match) {
      rules.push(match[0]);
    }
  }
  return rules;
}

const extractedBoldRules = extractRules(boldCss, 'bold', usedIcons);
const extractedFillRules = extractRules(fillCss, 'fill', usedIcons);

